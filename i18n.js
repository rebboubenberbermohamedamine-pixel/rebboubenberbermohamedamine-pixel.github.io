let current = "fr";

export function setUiLang(lang) {
  current = STRINGS[lang] ? lang : "fr";
  document.documentElement.lang = current;
  document.documentElement.dir = NATIVE_LANGS[current].dir;
}

export function uiLang() {
  return current;
}

/** Nom anglais de la langue maternelle, utilisé dans les consignes données à l'IA. */
export function nativeLanguageName(lang = current) {
  return NATIVE_LANGS[lang]?.english || "English";
}

/** Langue maternelle probable d'après le navigateur. */
export function guessNativeLang() {
  const nav = (navigator.languages || [navigator.language || "fr"]).map((l) => l.slice(0, 2).toLowerCase());
  return nav.find((l) => STRINGS[l]) || "fr";
}

export function t(key, vars = {}) {
  const s = STRINGS[current][key] ?? STRINGS.fr[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? vars[k] : `{${k}}`));
}
